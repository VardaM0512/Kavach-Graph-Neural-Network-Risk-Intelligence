Lang langOf(String code) => languages.firstWhere((l) => l.code == code, orElse: () => languages.first);

final Map<String, Map<String, String>> _tables = () {
  final t = <String, Map<String, String>>{'en': en, ...translationsA, ...translationsB, ...translationsC};
  // translations_d holds strings added later (My companies, model honesty); merge per language
  translationsD.forEach((lang, m) => t[lang] = {...?t[lang], ...m});
  return t;
}();

String translate(String lang, String key, [Map<String, Object?> args = const {}]) {
  var s = _tables[lang]?[key] ?? en[key] ?? key;
  args.forEach((k, v) => s = s.replaceAll('{$k}', '$v'));
  return s;
}

extension Tr on BuildContext {
  String t(String key, [Map<String, Object?> args = const {}]) =>
      translate(watch<AppState>().lang, key, args);
  /// Non-listening variant for callbacks.
  String tr(String key, [Map<String, Object?> args = const {}]) =>
      translate(read<AppState>().lang, key, args);
}

